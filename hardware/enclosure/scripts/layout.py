"""Shared, photo-derived geometry. No CAD dependency; writes Inventor constants."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "as-built-layout.json"


def dimensions(path=CONFIG):
    c = json.loads(Path(path).read_text())
    if c["roles"] != {"test": "TCS3448", "color": "TCS3448", "control": "AS7343"}:
        raise ValueError("Sensor roles must stay TCS=test/color, AS=control")
    if c["led_direction_y"] != -1 or c["as_y_mm"] <= c["tcs_y_mm"]:
        raise ValueError("This generator expects the photographed orientation: AS above TCS, LEDs toward -Y")
    s = c["strip"]
    d = dict(SensorX=c["sensor_x_mm"], TcsY=c["tcs_y_mm"], AsY=c["as_y_mm"],
             SpacerZ=c["breakout_back_z_mm"], SensorFaceZ=c["sensor_face_z_mm"],
             LedZ=c["led_face_z_mm"], StripW=s["width_mm"], StripT=s["thickness_mm"],
             StripLen=s["length_mm"], StripTopZ=s["top_z_mm"],
             LineT=s["test_from_tip_mm"], LineC=s["control_from_tip_mm"],
             ApertureD=c["default_aperture_mm"], XYCheckAllowance=c["xy_check_allowance_mm"])
    mid = (d["TcsY"] + d["AsY"]) / 2
    d.update(StripStopY=mid + (d["LineT"] + d["LineC"]) / 2,
             TLineY=mid - (d["LineT"] - d["LineC"]) / 2,
             CLineY=mid + (d["LineT"] - d["LineC"]) / 2,
             ChamberSplitY=mid,
             TcsLedY=d["TcsY"] - (15.875 - 8.509),
             AsLedY=d["AsY"] - (15.875 - 8.509),
             TcsHeaderY=d["TcsY"] + (8.509 - 2.54),
             AsHeaderY=d["AsY"] + (8.509 - 2.54),
             BoardsX0=d["SensorX"]-12.7, BoardsX1=d["SensorX"]+12.7,
             BoardsY0=d["TcsY"]-(17.78-8.509), BoardsY1=d["AsY"]+8.509,
             BlockX0=d["SensorX"]-6.9, BlockX1=d["SensorX"]+6.9,
             ChamberX0=d["SensorX"]-4, ChamberX1=d["SensorX"]+4,
             ChamberY0=d["TcsY"]-2.5, ChamberY1=d["AsY"]+2.5)
    for prefix in ("Tcs", "As"):
        d[prefix+"PinsY0"] = d[prefix+"HeaderY"] - 1.27
        d[prefix+"PinsY1"] = d[prefix+"HeaderY"] + 1.27
    if d["AsY"]-d["TcsY"] < 17.78:
        raise ValueError("Breakout outlines overlap")
    return c, d


def csharp(d):
    lines = ["// Generated by python3 scripts/layout.py from as-built-layout.json. Do not hand edit.",
             "// PROVISIONAL photo dimensions; check with the alignment gauge before full printing.",
             "public static class AsBuiltLayout", "{",
             f'    public const string LayoutSha256 = "{hashlib.sha256(CONFIG.read_bytes()).hexdigest()}";']
    lines += [f"    public const double {k} = {v:.6f};" for k, v in d.items()]
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="Fail if generated C# constants are stale")
    args = p.parse_args()
    _, d = dimensions()
    dest = ROOT / "scripts/AsBuiltLayout.cs"
    text = csharp(d)
    if args.check:
        if not dest.exists() or dest.read_text() != text:
            raise SystemExit("AsBuiltLayout.cs is stale; run python3 hardware/enclosure/scripts/layout.py")
        print("Shared Inventor constants match as-built-layout.json")
    else:
        dest.write_text(text)
        print(dest)
